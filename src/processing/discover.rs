//! Finding an `afni_proc.py` run and reading it from disk (the adapter).
//!
//! Only the directory you give is looked at: itself, its `proc.*` scripts,
//! its `<subj>.results` child named by the script, or, for a `*.results`
//! directory, the `proc.<subj>` script next to it. Parent trees are never
//! searched.

use std::collections::hash_map::DefaultHasher;
use std::fmt;
use std::hash::{Hash, Hasher};
use std::path::{Path, PathBuf};

