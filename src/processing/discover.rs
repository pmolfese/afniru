    #[test]
    fn locate_does_not_search_unrelated_trees() {
        let tmp = TempDir::new("unrelated");
        fs::create_dir_all(tmp.path().join("deep/er")).unwrap();
        fs::write(
            tmp.path().join("deep/er/proc.sub-01"),
            script_text("complete"),
        )
        .unwrap();
        // The script is two levels down: not found from here.
        assert!(matches!(
            locate(tmp.path()),
            Err(DiscoverError::NoScript(_))
        ));
        // A directory that is not *.results does not look at its parent.
        let sibling = tmp.path().join("other");
        fs::create_dir_all(&sibling).unwrap();
        fs::write(tmp.path().join("proc.other"), script_text("complete")).unwrap();
        assert!(matches!(locate(&sibling), Err(DiscoverError::NoScript(_))));
    }

